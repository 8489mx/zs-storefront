const initialLang = getSavedStorefrontLang();

export function syncDocumentLangAndDir(lang: StorefrontLang) {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'en' ? 'ltr' : 'rtl';
}

syncDocumentLangAndDir(initialLang);

i18n.use(initReactI18next).init({
  lng: initialLang,
  fallbackLng: 'ar',
  resources: {
    ar: { translation: {} },
    en: { translation: EN_STOREFRONT_TRANSLATIONS },
  },
  interpolation: {
    escapeValue: false,
  },
  parseMissingKeyHandler: (key: string, defaultValue?: string) => {
    if (i18n.language === 'en' && defaultValue) {
      const trimmed = defaultValue.trim();
      if (AR_TO_EN_PHRASES[trimmed]) {
        return AR_TO_EN_PHRASES[trimmed];
      }
    }
    return defaultValue !== undefined ? defaultValue : key;
  },
});

i18n.on('languageChanged', (lng) => {
  const normalized: StorefrontLang = lng === 'en' ? 'en' : 'ar';
  try {
    window.localStorage.setItem(STOREFRONT_LANG_STORAGE_KEY, normalized);
  } catch {}
  syncDocumentLangAndDir(normalized);
});

export function setStorefrontLanguage(lang: StorefrontLang) {
  i18n.changeLanguage(lang);
}

export function toggleStorefrontLanguage() {
  const next: StorefrontLang = i18n.language === 'en' ? 'ar' : 'en';
  i18n.changeLanguage(next);
  return next;
}

export function useStorefrontLang() {
  const { t: rawT, i18n: i18nInstance } = useTranslation();
  const lang: StorefrontLang = i18nInstance.language === 'en' ? 'en' : 'ar';
  const isEn = lang === 'en';
  const dir: 'ltr' | 'rtl' = isEn ? 'ltr' : 'rtl';

  const t = ((key: string, defaultValue?: any): string => {
    if (!isEn) {
      return typeof defaultValue === 'string' ? defaultValue : String(rawT(key, defaultValue));
    }
    if (typeof defaultValue === 'string') {
      const trimmed = defaultValue.trim();
      if (AR_TO_EN_PHRASES[trimmed]) {
        return AR_TO_EN_PHRASES[trimmed];
      }
    }
    const res = String(rawT(key, defaultValue));
    if (res && AR_TO_EN_PHRASES[res.trim()]) {
      return AR_TO_EN_PHRASES[res.trim()];
    }
    return res;
  }) as typeof rawT;

  const tr = (arText: string, enText?: string): string => {
    if (!isEn) return arText;
    if (enText) return enText;
    const trimmed = (arText || '').trim();
    return AR_TO_EN_PHRASES[trimmed] || arText;
  };

  return {
    lang,
    isEn,
    dir,
    t,
    tr,
    tProductName: (name?: string | null) => translateProductName(name, lang),
    tCategoryName: (cat?: string | null) => translateCategoryName(cat, lang),
    tOfferBadge: (badge?: string | null) => translateOfferBadge(badge, lang),
    tProductDesc: (desc?: string | null) => translateProductDesc(desc, lang),
    tPhrase: (text?: string | null) => translateKnownPhrase(text, lang),
    toggleLang: toggleStorefrontLanguage,
    setLang: setStorefrontLanguage,
  };
}

export default i18n;
